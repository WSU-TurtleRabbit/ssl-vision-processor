"""Benchmark ZED camera settings on the live field, one variant after another.

Each variant runs build/vision_processor on a copy of zed-config-lab.yml with a
few camera settings changed, with field geometry from a private backend on
isolated ports (never the default SSL ports), and records the published
detections. Field-corner pixels are scaled to the output size, which is exact
because every variant uses the same sensor mode.

The camera must be free: stop the live vision_processor first.

usage (from the repo root):
  .venv/bin/python tools/zed-benchmark.py [--seconds 30] [--out DIR] [--only NAME ...]
"""

from __future__ import annotations

import argparse
import json
import re
import signal
import socket
import statistics
import struct
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parent.parent
BASE_CONFIG = REPO / "zed-config-lab.yml"
GEOMETRY = REPO / "geometry-wrapper-lab-divB.yml"
VISION_PORT, GC_PORT, HTTP_PORT = 10998, 10994, 8791
GROUP = "224.5.23.2"

# name -> camera settings changed from zed-config-lab.yml (all at 60 fps, sensor mode 1280x720)
VARIANTS: dict[str, dict[str, Any]] = {
    "640x360": {"output_width": 640, "output_height": 360},
    "768x432 (now)": {"output_width": 768, "output_height": 432},
    "960x540": {"output_width": 960, "output_height": 540},
    "1280x720": {"output_width": 1280, "output_height": 720},
    "768x432 rectified": {"output_width": 768, "output_height": 432, "rectify": True},
}
# --sweep: 16:9 output sizes in 64 px steps from 768x432 to 1280x720 (same sensor mode, so corners scale exactly)
SWEEP: dict[str, dict[str, Any]] = {
    f"{w}x{w * 9 // 16}": {"output_width": w, "output_height": w * 9 // 16} for w in range(768, 1281, 64)
}
PIXEL_KEYS = ("line_corners", "outer_line_corners", "distortion_lines")


def scale_pixels(value: Any, factor: float) -> Any:
    if isinstance(value, list):
        return [scale_pixels(v, factor) for v in value]
    if isinstance(value, (int, float)):
        return round(float(value) * factor, 3)
    return value


def write_config(variant: dict[str, Any], run_dir: Path) -> Path:
    config = yaml.safe_load(BASE_CONFIG.read_text())
    base_width = config["camera"]["output_width"]
    config["camera"].update({"fps": 60, **variant})
    factor = config["camera"]["output_width"] / base_width
    for key in PIXEL_KEYS:
        if key in config.get("geometry", {}):
            config["geometry"][key] = scale_pixels(config["geometry"][key], factor)
    config["network"] = {
        "vision_ip": GROUP,
        "vision_port": VISION_PORT,
        "gc_ip": "224.5.23.1",
        "gc_port": GC_PORT,
    }
    config.setdefault("debug", {})["wait_for_geometry"] = True
    (run_dir / "img").mkdir(parents=True, exist_ok=True)
    (run_dir / "robot-heights.yml").write_text((REPO / "robot-heights.yml").read_text())
    path = run_dir / "config.yml"
    path.write_text(yaml.safe_dump(config, sort_keys=False))
    return path


def record(stop: threading.Event, frames: list[dict[str, Any]]) -> None:
    sys.path.insert(0, str(REPO / "wrapper_backend"))
    from proto import ssl_vision_wrapper_pb2  # generated by the backend on startup

    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM, socket.IPPROTO_UDP)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind(("", VISION_PORT))
    sock.setsockopt(
        socket.IPPROTO_IP,
        socket.IP_ADD_MEMBERSHIP,
        struct.pack("4sl", socket.inet_aton(GROUP), socket.INADDR_ANY),
    )
    sock.settimeout(0.5)
    while not stop.is_set():
        try:
            data, _ = sock.recvfrom(65536)
        except socket.timeout:
            continue
        packet = ssl_vision_wrapper_pb2.SSL_WrapperPacket()
        try:
            packet.ParseFromString(data)
        except Exception:
            continue
        if not packet.HasField("detection"):
            continue
        d = packet.detection
        frames.append(
            {
                "t_capture": d.t_capture,
                "t_sent": d.t_sent,
                "robots": [r.confidence for r in list(d.robots_blue) + list(d.robots_yellow)],
                "balls": [(b.x, b.y, b.confidence) for b in d.balls],
            }
        )
    sock.close()


def run_variant(name: str, variant: dict[str, Any], seconds: int, out: Path) -> dict[str, Any]:
    run_dir = out / re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    config = write_config(variant, run_dir)
    backend = subprocess.Popen(
        [sys.executable, "-m", "wrapper_backend", str(GEOMETRY), "--port", str(HTTP_PORT),
         "--vision-port", str(VISION_PORT), "--vision-config", str(config),
         "--frontend-dir", str(run_dir / "nofrontend"), "--vision-binary", "/nonexistent"],
        cwd=REPO, env={"PYTHONPATH": str(REPO), "PATH": "/usr/bin:/bin"},
        stdout=open(run_dir / "backend.log", "w"), stderr=subprocess.STDOUT,
    )
    time.sleep(4)
    frames: list[dict[str, Any]] = []
    stop = threading.Event()
    recorder = threading.Thread(target=record, args=(stop, frames))
    recorder.start()
    log = open(run_dir / "vp.log", "w")
    vp = subprocess.Popen([str(REPO / "build" / "vision_processor"), str(config)], cwd=run_dir, stdout=log, stderr=subprocess.STDOUT)
    time.sleep(seconds / 2)
    cpu = subprocess.run(["ps", "-o", "pcpu=", "-p", str(vp.pid)], capture_output=True, text=True).stdout.strip()
    time.sleep(seconds - seconds / 2)
    vp.send_signal(signal.SIGINT)
    vp.wait(timeout=20)
    time.sleep(1)
    stop.set()
    recorder.join()
    backend.terminate()
    backend.wait(timeout=10)
    log.close()

    text = (run_dir / "vp.log").read_text()
    if "[ZED] Opened" not in text:
        raise SystemExit(f"{name}: the camera did not open (is the live vision_processor still running?), see {run_dir / 'vp.log'}")
    ms = [float(m) for m in re.findall(r"status: detecting \| [\d.]+ fps, ([\d.]+) ms/frame", text)]
    frames = frames[len(frames) // 10:]  # skip warm-up while colours settle
    if len(frames) < 10:
        return {"name": name, "error": "no detections (calibration did not match?)", "dir": str(run_dir)}
    t = [f["t_capture"] for f in frames]
    with_ball = [f for f in frames if f["balls"]]
    ball_xy = [f["balls"][0][:2] for f in with_ball]
    jitter = (statistics.pstdev([p[0] for p in ball_xy]) ** 2 + statistics.pstdev([p[1] for p in ball_xy]) ** 2) ** 0.5 if len(ball_xy) > 1 else float("nan")
    robot_conf = [c for f in frames for c in f["robots"]]
    return {
        "name": name,
        "detections_per_s": len(frames) / (t[-1] - t[0]),
        "ms_per_frame": statistics.median(ms) if ms else float("nan"),
        "cpu_percent": float(cpu) if cpu else float("nan"),
        "robots_per_frame": statistics.mean(len(f["robots"]) for f in frames),
        "robot_confidence": statistics.mean(robot_conf) if robot_conf else 0.0,
        "ball_percent": 100 * len(with_ball) / len(frames),
        "ball_confidence": statistics.mean(f["balls"][0][2] for f in with_ball) if with_ball else 0.0,
        "ball_jitter_mm": jitter,
        "latency_ms": 1000 * statistics.median(f["t_sent"] - f["t_capture"] for f in frames),
        "max_gap_ms": 1000 * max(b - a for a, b in zip(t, t[1:])),
        "dir": str(run_dir),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seconds", type=int, default=30)
    parser.add_argument("--out", type=Path, default=Path("/tmp") / f"zed-benchmark-{time.strftime('%Y%m%d-%H%M%S')}")
    parser.add_argument("--only", nargs="*", help="variant names to run (default: all)")
    parser.add_argument("--sweep", action="store_true", help="run the output-size sweep 768x432 .. 1280x720 instead")
    args = parser.parse_args()
    # -f: the process name is truncated to 15 characters ("vision_processo"), so -x never matches
    if subprocess.run(["pgrep", "-f", "/vision_processor( |$)"], capture_output=True).returncode == 0:
        raise SystemExit("A vision_processor is running and holds the camera. Stop it first (Services panel or Ctrl+C).")
    results = []
    for name, variant in (SWEEP if args.sweep else VARIANTS).items():
        if args.only and name not in args.only:
            continue
        print(f"running {name} for {args.seconds} s ...", flush=True)
        results.append(run_variant(name, variant, args.seconds, args.out))
    (args.out / "results.json").write_text(json.dumps(results, indent=2))

    print("\n| variant | det/s | ms/frame | CPU % | robots/frame | robot conf | ball % | ball conf | ball jitter mm | latency ms | max gap ms |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in results:
        if "error" in r:
            print(f"| {r['name']} | {r['error']} |" + " |" * 9)
            continue
        print(f"| {r['name']} | {r['detections_per_s']:.1f} | {r['ms_per_frame']:.1f} | {r['cpu_percent']:.0f} | {r['robots_per_frame']:.2f} | {r['robot_confidence']:.3f} | {r['ball_percent']:.1f} | {r['ball_confidence']:.3f} | {r['ball_jitter_mm']:.1f} | {r['latency_ms']:.1f} | {r['max_gap_ms']:.0f} |")
    print(f"\nraw results: {args.out / 'results.json'}")


if __name__ == "__main__":
    main()
